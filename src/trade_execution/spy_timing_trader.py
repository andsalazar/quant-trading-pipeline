def send_email_alert(subject, body):
    """Send email alert via Gmail"""
    if not CONFIG['send_email']:
        return
    try:
        msg = MIMEMultipart()
        msg['Subject'] = subject
        msg['From'] = EMAIL_USER
        msg['To'] = EMAIL_TO
        msg.attach(MIMEText(body, 'plain'))
        with smtplib.SMTP_SSL('smtp.gmail.com', 465) as server:
            server.login(EMAIL_USER, EMAIL_PASS)
            server.send_message(msg)
        print(f"  [OK] Email sent: {subject}")
    except Exception as e:
        print(f"  [!] Email failed: {e}")


def load_signal(signal_file):
    """Load and validate the SPY timing signal"""
    if not os.path.exists(signal_file):
        raise FileNotFoundError(f"Signal file not found: {signal_file}")

    df = pd.read_csv(signal_file)
    if len(df) == 0:
        raise ValueError("Signal file is empty")

    row = df.iloc[0]

    signal = {
        'signal_date': str(row['signal_date']),
        'execute_at': str(row.get('execute_at', 'NEXT_OPEN')),
        'signal': str(row['signal']).upper(),
        'ensemble_prob': float(row['ensemble_prob']),
        'confidence_pct': float(row['confidence_pct']),
        'generated_at': str(row.get('generated_at', '')),
    }

    # Validate signal value
    if signal['signal'] not in ('BUY', 'CASH'):
        raise ValueError(f"Invalid signal: {signal['signal']} (expected BUY or CASH)")

    return signal


def check_signal_freshness(signal, max_age_bdays):
    """Ensure the signal is not stale (using business days to handle weekends)"""
    try:
        signal_date = pd.to_datetime(signal['signal_date'])
        now = pd.Timestamp.now()
        # Count business days between signal and now
        bday_age = len(pd.bdate_range(signal_date, now)) - 1  # subtract 1 since range is inclusive
        calendar_age = (now - signal_date).days
        if bday_age > max_age_bdays:
            raise ValueError(
                f"Signal is {bday_age} business days old ({calendar_age} calendar days, "
                f"signal_date={signal['signal_date']}). "
                f"Maximum allowed: {max_age_bdays} business days. Run the prediction pipeline first."
            )
        return bday_age
    except Exception as e:
        if 'Signal is' in str(e):
            raise
        print(f"  [!] Could not parse signal_date: {signal['signal_date']}. Proceeding anyway.")
        return -1


