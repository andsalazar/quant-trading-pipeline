"""
IBKR SPY Timing Trader
======================
Executes the SPY market-timing strategy via Interactive Brokers.

Logic:
  - Reads spy_timing_signal_latest.csv (generated by 06_02_predict_spy_timing.py)
  - BUY  → Sell any non-SPY positions (e.g., IAU/gold), buy SPY with all available cash
  - CASH → Sell SPY position, hold cash

Features:
  - Fractional shares via cashQty orders (deploy ~100% of capital)
  - Staleness guard: refuses to trade on signals older than 2 calendar days
  - Minimum confidence threshold (configurable)
  - Trade logging to spy_timing_trade_log.csv
  - Optional email alerts via Gmail

Requirements:
    pip install ib_insync pandas python-dotenv

Usage:
    python ibkr_spy_timing_trader.py          # Interactive mode
    python ibkr_spy_timing_trader.py --auto   # No confirmation (for Task Scheduler)
    python ibkr_spy_timing_trader.py --paper   # Use paper trading port 7497
"""

